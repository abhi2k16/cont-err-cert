def tex_escape(text: str) -> str:
    return (text.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")
            .replace("^", r"\^{}").replace("<=", r"$\le$").replace(">=", r"$\ge$"))


def write(name: str, rows: list[str], header: str) -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / name).write_text(f"% generated by experiments/tables.py; seeds {list(SEEDS)}\n{header}\n" + "\n".join(rows)
                               + "\n\\hline\n\\end{tabular}\n", encoding="utf-8")


def table_e1() -> None:
    rows = []
    for problem in ("membrane", "block"):
        for key, label in CORRECTIONS.items():
            parts = [json.loads((RESULTS / "e1_exactness" / f"{problem}_seed{s}.json").read_text())[key] for s in SEEDS]
            q, nc = sum(p["queries"] for p in parts), sum(p["n_condition"] for p in parts)
            dev = max(p["max_abs_eff_minus_1_where_condition"] for p in parts)
            meds = [p["eff_median_other"] for p in parts if p["eff_median_other"] is not None]
            maxs = [p["eff_max_other"] for p in parts if p["eff_max_other"] is not None]
            viol = sum(p["exactness_violations"] + p["bound_violations"] for p in parts)
            rows.append(f"{problem} & {label} & {q} & {100 * nc / q:.0f}\\,\\% & "
                        f"{('--' if nc == 0 else f'{dev:.1e}')} & {np.median(meds):.2f} & {max(maxs):.2f} & {viol} \\\\")
    write("e1_exactness.tex", rows, "\\begin{tabular}{llrrrrrr}\n\\hline\nproblem & correction & queries & (C) holds & "
          "$\\max|\\mathrm{eff}-1|$ under (C) & median eff.\\ otherwise & max eff.\\ otherwise & violations \\\\\n\\hline")


def table_e2() -> None:
    rows = []
    for problem in ("membrane", "block"):
        parts = [json.loads((RESULTS / "e2_support_floor" / f"{problem}_seed{s}.json").read_text()) for s in SEEDS]
        rate = np.mean([p["rate_full"] for p in parts])
        for name, label in (("omit_i", r"all rows but $i^\ast$"), ("omit_A", r"$\mathcal A_+\setminus\{i^\ast\}$")):
            floor = min(p[name]["min_ratio_to_floor"] for p in parts)
            stall = min(p[name]["min_ratio_to_full"] for p in parts)
            viol = sum(p[name]["floor_violations"] + p[name]["stall_violations"] for p in parts)
            rows.append(f"{problem} & {label} & {rate:.3f} & {floor:.3f} & {stall:.0f} & {viol} \\\\")
    write("e2_support_floor.tex", rows, "\\begin{tabular}{llrrrr}\n\\hline\nproblem & support $S$ & rate of full S1 & "
          "$\\min\\Delta^\\star(\\ell_S)/\\sigma_S$ & $\\min\\Delta^\\star(\\ell_S)/\\Delta^\\star(\\ell^\\star)$ & violations \\\\\n\\hline")


def table_e3() -> None:
    agg = {}
    for s in SEEDS:
        for name, v in json.loads((RESULTS / "e3_random" / f"summary_seed{s}.json").read_text())["statements"].items():
            a = agg.setdefault(name, {"checked": 0, "viol": 0, "worst": np.inf, "med": [], "min": [], "max": []})
            a["checked"] += v["checked"]
            a["viol"] += v["violations"]
            a["worst"] = min(a["worst"], v["worst_margin"])
            if "ratio_median" in v:
                a["med"].append(v["ratio_median"]), a["min"].append(v["ratio_min"]), a["max"].append(v["ratio_max"])
    rows = []
    for name, a in agg.items():
        ratio = (f"{np.median(a['med']):.3f} ({min(a['min']):.3f}--{max(a['max']):.3f})" if a["med"] else "identity")
        rows.append(f"{LABELS.get(name, tex_escape(name))} & {a['checked']} & {a['viol']} & {('--' if not np.isfinite(a['worst']) else format(a['worst'], '.1e'))} & {ratio} \\\\")
    write("e3_random.tex", rows, "\\begin{tabular}{lrrrl}\n\\hline\nstatement & checks & violations & worst margin & "
          "lhs/rhs: median (min--max) \\\\\n\\hline")


def table_benchmarks() -> None:
    """Benchmark summary read from the problem objects and the settings in config (nothing typed by hand except the element names)."""
    elements = {"membrane": "Quad4, scalar Laplace (2D)", "block": "Hex8, linear elasticity (3D)"}
    rows = []
    for name in ("membrane", "block"):
        problem, cfg = make_problem(name), SETTINGS[name]
        mesh = (f"${problem.n}\\times{problem.n}$ cells" if name == "membrane"
                else f"${problem.n_xy}\\times{problem.n_xy}\\times{problem.nz}$ cells")
        sizes = ", ".join(str(r) for r in cfg["r_primal"])
        rows.append((name, elements[name], mesh, problem.n_dof, problem.n_contact, cfg["n_train"], cfg["n_test"], sizes))
    labels = ["element", "mesh", "unknowns $N$", "contact rows $n_c$", "training snapshots", "test queries per seed", "primal basis sizes $r$"]
    body = [f"{lab} & " + " & ".join(str(row[k + 1]) for row in rows) + " \\\\" for k, lab in enumerate(labels)]
    write("benchmarks.tex", body, "\\begin{tabular}{lll}\n\\hline\n & " + " & ".join(r[0] for r in rows) + " \\\\\n\\hline")


def main() -> int:
    setup_logging()
    try:
        table_e1(), table_e2(), table_e3(), table_benchmarks()
    except FileNotFoundError as exc:
        LOG.error("missing result file: %s (run the experiments first)", exc)
        return EXIT_BAD_INPUT
    LOG.info("wrote %s", ", ".join(["e1_exactness.tex", "e2_support_floor.tex", "e3_random.tex", "benchmarks.tex"]))
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
